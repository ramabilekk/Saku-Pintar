package com.example.ai

import android.content.Context
import android.content.Intent
import android.util.Log
import com.example.BuildConfig
import com.google.firebase.FirebaseApp
import com.google.firebase.appcheck.FirebaseAppCheck
import com.google.firebase.appcheck.debug.DebugAppCheckProviderFactory
import com.google.firebase.appcheck.recaptcha.RecaptchaAppCheckProviderFactory

private const val TAG = "AppCheckInit"

private const val DEBUG_TOKEN_EXTRA = "FIREBASE_APPCHECK_DEBUG_TOKEN"
private const val DEBUG_STORE_PREFIX = "com.google.firebase.appcheck.debug.store."
private const val APPCHECK_TOKEN_STORE_PREFIX = "com.google.firebase.appcheck.store."
private const val DEBUG_SECRET_KEY = "com.google.firebase.appcheck.debug.DEBUG_SECRET"
private const val VERIFIED_INTENT_TOKEN_KEY = "aistudio_verified_intent_debug_token"
private const val RECAPTCHA_SITE_KEY_RES = "recaptcha_site_key"

fun configureAppCheck(context: Context, intent: Intent?) {
  try {
    if (FirebaseApp.getApps(context).isEmpty()) {
      FirebaseApp.initializeApp(context)
    }

    if (BuildConfig.DEBUG) {
      val debugToken = intent?.getStringExtra(DEBUG_TOKEN_EXTRA)
      val persistenceKey = FirebaseApp.getInstance().persistenceKey
      val prefs = context.getSharedPreferences(
        "$DEBUG_STORE_PREFIX$persistenceKey",
        Context.MODE_PRIVATE,
      )

      if (!debugToken.isNullOrEmpty()) {
        // Synchronous commit() ensures the debug token is persisted before DebugAppCheckProviderFactory reads it.
        prefs.edit()
          .putString(DEBUG_SECRET_KEY, debugToken)
          .putString(VERIFIED_INTENT_TOKEN_KEY, debugToken)
          .commit()
        Log.d(TAG, "App Check debug secret configured successfully.")
      } else {
        Log.w(TAG, "No debug token found in Intent extra.")
      }

      // Only use DebugAppCheckProviderFactory if a genuine debug token was supplied via the
      // AI Studio emulator launch intent. Never trust a random UUID auto-generated by
      // DebugAppCheckProviderFactory on a real user phone.
      val verifiedIntentToken = prefs.getString(VERIFIED_INTENT_TOKEN_KEY, null)
      if (!BuildConfig.IS_GITHUB_RELEASE_BUILD && !verifiedIntentToken.isNullOrEmpty()) {
        if (prefs.getString(DEBUG_SECRET_KEY, null) != verifiedIntentToken) {
          prefs.edit().putString(DEBUG_SECRET_KEY, verifiedIntentToken).commit()
        }
        FirebaseAppCheck.getInstance().installAppCheckProviderFactory(
          DebugAppCheckProviderFactory.getInstance(),
        )
        Log.d(TAG, "DebugAppCheckProviderFactory installed with verified launch token.")
      } else {
        // Purge any unregistered random UUID that DebugAppCheckProviderFactory may have
        // generated on an earlier install, along with any cached invalid App Check token.
        if (prefs.contains(DEBUG_SECRET_KEY) || prefs.contains(VERIFIED_INTENT_TOKEN_KEY)) {
          prefs.edit()
            .remove(DEBUG_SECRET_KEY)
            .remove(VERIFIED_INTENT_TOKEN_KEY)
            .commit()
          context.getSharedPreferences(
            "$APPCHECK_TOKEN_STORE_PREFIX$persistenceKey",
            Context.MODE_PRIVATE,
          ).edit().clear().commit()
          Log.d(TAG, "Cleared stale unregistered debug App Check token from device storage.")
        }
        installRecaptchaAppCheck(context)
      }
    } else {
      installRecaptchaAppCheck(context)
    }
  } catch (e: Exception) {
    Log.e(TAG, "Failed to initialize Firebase App Check", e)
  }
}

private fun installRecaptchaAppCheck(context: Context) {
  val resId = context.resources.getIdentifier(RECAPTCHA_SITE_KEY_RES, "string", context.packageName)
  if (resId != 0) {
    val siteKey = context.getString(resId)
    if (siteKey.isNotBlank()) {
      FirebaseAppCheck.getInstance().installAppCheckProviderFactory(
        RecaptchaAppCheckProviderFactory.getInstance(siteKey),
      )
      Log.d(TAG, "RecaptchaAppCheckProviderFactory installed.")
    } else {
      Log.e(TAG, "recaptcha_site_key resource string is blank.")
    }
  } else {
    Log.e(TAG, "recaptcha_site_key string resource not found in package.")
  }
}
